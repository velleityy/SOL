function replaceText(original, lang) {
  if (lang === 'id') return original;
  const clean = original.trim();
  if (!Object.prototype.hasOwnProperty.call(translations[lang], clean)) return original;
  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  return leading + translations[lang][clean] + trailing;
}

function setLanguage(lang) {
  const selected = ['en', 'zh'].includes(lang) ? lang : 'id';
  textNodes.forEach(({node, original}) => { node.textContent = replaceText(original, selected); });
  const meta = metadata[selected];
  document.documentElement.lang = selected === 'zh' ? 'zh-CN' : selected;
  document.title = meta.title;
  document.querySelector('meta[name="description"]').content = meta.description;

  const labels = {
    '#nav': meta.nav,
    '.menu-toggle': meta.menu,
    '.language-switcher': meta.language,
    '.brand': meta.home,
    '.hero-image': meta.factory,
    '.hero-stats': meta.summary,
    '.logo-carousel': meta.clients,
    '.carousel-prev': meta.previous,
    '.carousel-next': meta.next,
    '.qc-flow': meta.quality
  };
  Object.entries(labels).forEach(([selector, label]) => {
    document.querySelector(selector).setAttribute('aria-label', label);
  });
  document.querySelectorAll('img[data-photo]').forEach(img => {
    img.alt = imageAlt[selected][img.dataset.photo];
  });
  document.querySelectorAll('.language-switcher button').forEach(btn => {
    const active = btn.dataset.lang === selected;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });

  // Language switching also works when browser privacy settings block storage.
  try { localStorage.setItem('sol-language', selected); } catch {}
}

document.querySelectorAll('.language-switcher button').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});
let savedLanguage = 'id';
try { savedLanguage = localStorage.getItem('sol-language') || 'id'; } catch {}
setLanguage(savedLanguage);

