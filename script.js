function replaceText(original, lang) {
  if (lang === 'id') return original;
  const clean = original.trim();
  const value = translations[lang][clean];
  if (!value) return original;
  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  return leading + value + trailing;
}

function setLanguage(lang) {
  const selected = translations[lang] ? lang : 'id';
  textNodes.forEach(({node, original}) => { node.textContent = replaceText(original, selected); });
  const meta = metadata[selected];
  document.documentElement.lang = selected === 'zh' ? 'zh-CN' : selected;
  document.title = meta.title;
  document.querySelector('meta[name="description"]').content = meta.description;
  document.querySelector('#nav').setAttribute('aria-label', meta.nav);
  document.querySelector('.language-switcher').setAttribute('aria-label', meta.language);
  document.querySelector('.brand').setAttribute('aria-label', meta.home);
  document.querySelector('.hero-image').setAttribute('aria-label', meta.factory);
  document.querySelector('.hero-stats').setAttribute('aria-label', meta.summary);
  document.querySelectorAll('.product-card img, .process-visual img').forEach((img, index) => {
    img.alt = imageAlt[selected][index];
  });
  document.querySelectorAll('.language-switcher button').forEach(btn => {
    const active = btn.dataset.lang === selected;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
  localStorage.setItem('sol-language', selected);
}

document.querySelectorAll('.language-switcher button').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});
setLanguage(localStorage.getItem('sol-language') || 'id');

const observer = new IntersectionObserver(entries => entries.forEach(entry => {
  if (entry.isIntersecting) {
    entry.target.classList.add('visible');
    observer.unobserve(entry.target);
  }
}), {threshold:.12});
document.querySelectorAll('.reveal').forEach(el => observer.observe(el));
